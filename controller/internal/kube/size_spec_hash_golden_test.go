package kube

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"testing"

	"github.com/vtmocanu/uzi/controller/internal/preset"
	"github.com/vtmocanu/uzi/controller/internal/protocol"
)

// The size SPEC-HASH golden: the pod spec-hash of every builtin hosted size across the
// tiers the renderer supports, captured BEFORE any change to how a size name resolves.
// A later path that resolves sizes from another source must reproduce these bytes
// exactly, or every live worker would see spec drift and roll.
//
// Regenerate with `UPDATE_GOLDEN=1 go test ./internal/kube/ -run SizeSpecHash`.
const sizeSpecHashFixture = "testdata/size_spec_hash_golden.json"

// sizeSpecHashCase is one golden row: the key, the config and the desired worker whose
// hash is recorded. Reusable so another test can recompute each row through a different
// resolver path.
type sizeSpecHashCase struct {
	key string
	cfg RenderConfig
	w   protocol.DesiredWorker
}

// sizeSpecHashCases builds every row. Combinations:
//   - plain and docker tiers, persistent and run-bound (ephemeral);
//   - the isolated lane, run-bound only (the api provisions it per run; there is no
//     persistent isolated worker).
//
// Excluded: isolated+docker, which the renderer refuses (the lane never carries DinD).
func sizeSpecHashCases(t *testing.T) []sizeSpecHashCase {
	t.Helper()
	cfg := dockerTestConfig()
	cfg.IsolatedNamespace = "uzi-workers-isolated"

	names := preset.SizeNames()
	sort.Strings(names)

	var out []sizeSpecHashCase
	for _, size := range names {
		for _, tier := range []string{"plain", "docker", "isolated"} {
			for _, mode := range []string{"persistent", "run-bound"} {
				if tier == "isolated" && mode == "persistent" {
					continue
				}
				w := protocol.DesiredWorker{
					ID:        "size-hash-golden",
					Template:  "base",
					Size:      size,
					Docker:    tier == "docker",
					Isolated:  tier == "isolated",
					Ephemeral: mode == "run-bound",
				}
				out = append(out, sizeSpecHashCase{
					key: fmt.Sprintf("%s/%s/%s", size, tier, mode),
					cfg: cfg,
					w:   w,
				})
			}
		}
	}
	return out
}

func buildSizeSpecHashGolden(t *testing.T) map[string]string {
	t.Helper()
	r := testResolver(t)
	got := map[string]string{}
	for _, c := range sizeSpecHashCases(t) {
		spec, err := r.Resolve(c.w.Template, c.w.Size)
		if err != nil {
			t.Fatalf("Resolve(%q, %q) for %s: %v", c.w.Template, c.w.Size, c.key, err)
		}
		if _, dup := got[c.key]; dup {
			t.Fatalf("duplicate golden key %q", c.key)
		}
		got[c.key] = SpecHashOf(c.cfg, c.w, spec)
	}
	return got
}

func TestSizeSpecHashGolden(t *testing.T) {
	got := buildSizeSpecHashGolden(t)
	if len(got) == 0 {
		t.Fatal("no size spec-hash rows were produced")
	}

	if os.Getenv("UPDATE_GOLDEN") == "1" {
		raw, err := json.MarshalIndent(got, "", "  ")
		if err != nil {
			t.Fatalf("marshal: %v", err)
		}
		raw = append(raw, '\n')
		if err := os.MkdirAll(filepath.Dir(sizeSpecHashFixture), 0o755); err != nil { //nolint:gosec // G301: test fixture dir, regenerated by hand
			t.Fatalf("mkdir testdata: %v", err)
		}
		if err := os.WriteFile(sizeSpecHashFixture, raw, 0o644); err != nil { //nolint:gosec // G306: committed test fixture, world-readable like the repo
			t.Fatalf("write golden: %v", err)
		}
		t.Log("golden file updated")
		return
	}

	rawWant, err := os.ReadFile(sizeSpecHashFixture)
	if err != nil {
		t.Fatalf("read golden (regenerate with UPDATE_GOLDEN=1): %v", err)
	}
	var want map[string]string
	if err := json.Unmarshal(rawWant, &want); err != nil {
		t.Fatalf("parse golden: %v", err)
	}

	keys := make([]string, 0, len(got)+len(want))
	for k := range got {
		keys = append(keys, k)
	}
	for k := range want {
		if _, ok := got[k]; !ok {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		g, inGot := got[k]
		w, inWant := want[k]
		switch {
		case !inWant:
			t.Fatalf("row %q is produced by the test but missing from the golden (regenerate with UPDATE_GOLDEN=1 only if deliberate)", k)
		case !inGot:
			t.Fatalf("row %q is in the golden but no longer produced by the test", k)
		case g != w:
			t.Fatalf("spec hash drifted for %q: got %s, golden %s (a deliberate pod-spec change rolls every live worker)", k, g, w)
		}
	}
}
